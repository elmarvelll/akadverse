// Compose one transaction-capable runtime client; public migrations and standalone schema sync retain their input.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
let schema = readFileSync(resolve(root, "prisma/schema.prisma"), "utf8");
if (/@@schema\(|\bschemas\s*=/.test(schema)) throw new Error("Public schema ownership changed; review the runtime schema composer before generating.");
schema = schema.replace('  directUrl = env("DIRECT_URL")', '  directUrl = env("DIRECT_URL")\n  schemas   = ["public", "marketplace"]');
schema = schema.replace(/((?:model|enum) \w+ \{[\s\S]*?)(\n\})/g, '$1\n\n  @@schema("public")$2');
schema = schema.replace('model User {', 'model User {\n  marketplaceAccount AccountState?');
schema = schema.replace('model Business {', 'model Business {\n  deliveryPrices BusinessDeliveryPrice[]');
schema += '\n' + readFileSync(resolve(root, "prisma/marketplace-runtime/extensions.prisma"), "utf8");
const path = resolve(root, "prisma/marketplace-runtime/schema.prisma");
mkdirSync(dirname(path), { recursive: true });
writeFileSync(path, '// GENERATED by scripts/generate-core-prisma.mjs. Never migrate or db push this runtime union.\n' + schema);
if (!process.argv.includes("--schema-only")) {
  const result = spawnSync(process.execPath, [resolve(root, "node_modules/prisma/build/index.js"), "generate", "--schema", path], { cwd: root, stdio: "inherit" });
  process.exitCode = result.status ?? 1;
}
