test("history filters use scheduled dates and leave ordinary tasks and analytics unchanged", async () => {
  const f = fixture(), service = f.service(), habit = await service.save(input({ startDate: "2029-12-01" }));
  await service.record(habit.id, "2029-12-01", "completed"); await service.record(habit.id, "2030-01-14", "missed");
  await service.synchronize({ start: "2030-01-15", end: "2030-01-15" });
  const ordinary = await f.tasks().createTask({ title: "Ordinary", priority: "low", dueDate: "2020-01-01" });
  const now = new Date("2030-01-15T10:00:00Z"), records = await f.tasks().listTasks(), all = todoTasks(records, [habit], "Africa/Lagos", now);
  assert.equal(taskStatusCounts(all, "Africa/Lagos", now).completed, 1); assert.equal(taskStatusCounts(all, "Africa/Lagos", now).missed, 1);
  const today = filterHabitHistory(all, "today", "Africa/Lagos", now); assert.ok(today.some(item => item.id === ordinary.id)); assert.equal(today.some(item => item.status === "completed"), false);
  assert.equal(filterHabitHistory(all, "month", "Africa/Lagos", now).some(item => item.dueDate === "2029-12-01"), false);
  const metrics = taskAnalytics(records, "development-student", { start: "2030-01-15", end: "2030-01-15" }, "Africa/Lagos", now);
  assert.equal(metrics.daily.reduce((sum, row) => sum + row.count, 0), 1);
});
