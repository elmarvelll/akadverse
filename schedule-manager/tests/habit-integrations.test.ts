const input = { name: "Exercise", description: "Practice", type: "task" as const, frequency: "daily" as const, weekdays: [], priority: "high" as const, time: "18:00" };
function fixture() {
  const values = new Map<string, string>();
  const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); } };
  const tasks = new TaskService(new BrowserTaskRepository(() => storage), developmentIdentity, () => new Date("2030-01-15T12:00:00Z"));
  const schedules = new BrowserScheduleRepository(() => storage);
  const habits = new HabitService(new BrowserHabitRepository(() => storage), tasks, schedules, developmentIdentity, sampleAcademics, () => new Date("2030-01-15T12:00:00Z"));
  return { values, tasks, schedules, habits };
}
test("destination projections create today's task only while future habit events retain real slots and conflict behavior", async () => {
  const f = fixture(); await f.habits.save(input);
  const event = await f.habits.save({ ...input, type: "event", time: "18:00", end: "19:00", frequency: "weekdays", weekdays: [1, 3, 5] });
  await f.habits.save({ ...input, name: "Overlapping habit", type: "event", time: "18:30", end: "19:30" });
  const range = { start: "2030-01-15", end: "2030-01-31" };
  await f.habits.synchronize(range, { tasks: "today" });
  assert.deepEqual((await f.tasks.listTasks()).map(task => task.dueDate), ["2030-01-15"]);
  let data = await f.schedules.load();
  const wednesday = selectScheduleEvents(data, "development-student", { date: "2030-01-16" });
  const projected = wednesday.find(item => item.source.kind === "habit" && item.source.habitId === event.id)!;
  assert.equal(projected.slot.start, "18:00"); assert.equal(projected.slot.end, "19:00"); assert.equal(projected.priority, "high");
  assert.equal(scheduleConflicts(wednesday, [], "development-student").get(projected.id)!.length, 1);
  assert.equal(selectScheduleEvents(data, "development-student", { date: "2030-01-17" }).some(item => item.source.kind === "habit" && item.source.habitId === event.id), false);
  const before = JSON.stringify(data);
  await f.habits.synchronize({ start: "2030-01-16", end: "2030-01-16" }, { tasks: "today" });
  data = await f.schedules.load(); assert.equal(JSON.stringify(data), before);
  assert.equal((await f.tasks.listTasks()).length, 1);
});
test("legacy source aliases reuse their original local date; conflicting outcomes are reported without rewriting storage", async () => {
  const f = fixture(), habit = await f.habits.save(input);
  await f.tasks.receiveHabitOccurrence({ title: input.name, priority: input.priority, dueTime: input.time, habitId: habit.id, habitName: habit.revisions[0].name, occurrenceId: "legacy-slot", scheduledDate: "2030-01-15" }, ["2030-01-15"]);
  const [item] = await f.habits.synchronize({ start: "2030-01-15", end: "2030-01-15" });
  assert.equal((await f.tasks.listTasks()).length, 1); assert.equal(item.task!.source.kind === "habit" && item.task!.source.occurrenceId, "legacy-slot");
  const original = (await f.tasks.listTasks())[0];
  await f.tasks.completeTask(original.id);
  const raw = JSON.parse(f.values.get(TASK_STORAGE_KEY)!);
  raw.tasks.push({ ...original, id: "old-alias", source: { ...original.source, occurrenceId: "old-alias" } });
  f.values.set(TASK_STORAGE_KEY, JSON.stringify(raw));
  const before = [...f.values];
  assert.equal(habitDuplicateConflicts(await f.tasks.listTasks()).length, 1);
  await assert.rejects(f.habits.synchronize({ start: "2030-01-15", end: "2030-01-15" }), /Conflicting duplicate habit outcomes/);
  assert.deepEqual([...f.values], before);
  const analytics = taskAnalytics(await f.tasks.listTasks(), "development-student", { start: original.createdAt.slice(0, 10), end: original.createdAt.slice(0, 10) }, "Africa/Lagos", new Date());
  assert.ok(analytics.warnings.some(warning => warning.includes("duplicate habit outcomes")));
  assert.equal(analytics.statuses.reduce((sum, item) => sum + item.count, 0), 1);
});
test("the shared Habit badge and historical recurrence details are readable and omit timezone", () => {
  const require = createRequire(import.meta.url), exports: Record<string, unknown> = {};
  const source = readFileSync(new URL("../src/features/habits/HabitLabel.tsx", import.meta.url), "utf8");
  const compiled = ts.transpileModule(source, { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS } }).outputText;
  new Function("require", "exports", compiled)((name: string) => name === "./domain" ? habitDomain : require(name), exports);
  const Badge = exports.HabitBadge as ComponentType;
  assert.match(renderToStaticMarkup(createElement(Badge)), /class="badge habit-badge">Habit/);
  const Recurrence = exports.HabitRecurrence as ComponentType<{ habit?: habitDomain.Habit; date: string }>;
  const habit: habitDomain.Habit = { id: "one", ownerId: "student", timezone: "Africa/Lagos", createdDate: "2030-01-01", createdAt: "2030-01-01T00:00:00Z", revisions: [{ ...input, frequency: "weekdays", weekdays: [1, 3, 5], effectiveDate: "2030-01-01", at: "2030-01-01T00:00:00Z", archived: false }, { ...input, effectiveDate: "2030-02-01", at: "2030-01-31T00:00:00Z", archived: false }] };
  const markup = renderToStaticMarkup(createElement(Recurrence, { habit, date: "2030-01-16" }));
  assert.match(markup, /Monday, Wednesday, Friday/); assert.match(markup, /one occurrence/);
  assert.doesNotMatch(markup, /Africa\/Lagos|UTC|GMT/);
});
