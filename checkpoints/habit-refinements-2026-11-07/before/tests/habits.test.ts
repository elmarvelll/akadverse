test("frequency, time, and type edits preserve today, past context and recorded future outcomes", async () => {
  const f = fixture(), service = f.service(), habit = await service.save(input());
  let items = await service.synchronize({ start: "2030-01-30", end: "2030-02-02" });
  await service.record(habit.id, "2030-02-02", "completed");
  const before = (await f.tasks().listTasks()).find(task => task.dueDate === "2030-01-30")!;
  await service.save(input({ frequency: "weekdays", weekdays: [5], time: "20:00" }), habit.id);
  items = await service.synchronize({ start: "2030-01-30", end: "2030-02-02" });
  assert.deepEqual(items.map(item => item.date), ["2030-01-30", "2030-02-01", "2030-02-02"]);
  assert.equal(items[0].task!.dueTime, "18:00"); assert.equal(items[0].task!.id, before.id);
  assert.equal(items[1].task!.dueTime, "20:00"); assert.equal(items[2].task!.dueTime, "18:00"); assert.equal(outcome(items[2]), "completed");
  const withdrawn = (await f.tasks().listTasks()).find(task => task.dueDate === "2030-01-31")!;
  assert.equal(withdrawn.habitWithdrawn, true);
  assert.equal(queryTasks([withdrawn], { timezone: "Africa/Lagos", instant: new Date("2030-01-30T10:00:00Z") }).length, 0);
  await assert.rejects(f.tasks().completeTask(withdrawn.id), /withdrawn/);
  await service.save(input({ type: "event", time: "07:00", end: "08:00" }), habit.id);
  items = await service.synchronize({ start: "2030-01-30", end: "2030-02-02" });
  assert.ok(items.find(item => item.date === "2030-01-31")!.event);
  assert.equal(items.find(item => item.date === "2030-02-02")!.event, undefined);
  assert.equal(outcome(items.find(item => item.date === "2030-02-02")!), "completed");
});
