test("event habits project real slots and priorities, surface conflicts, and use the existing schedule outcome record", async () => {
  const today = localNow("Africa/Lagos").date, f = fixture(new Date().toISOString()), service = f.service();
  const habit = await service.save(input({ type: "event", time: "00:00", end: "00:01" }));
  const other = await service.save(input({ name: "Conflicting practice", type: "event", time: "00:00", end: "00:02" }));
  const range = { start: today, end: addDays(today, 1) };
  let items = await service.synchronize(range);
  const event = items.find(item => item.habitId === habit.id && item.date === today)!.event!;
  assert.equal(event.priority, "high"); assert.equal(event.slot.start, "00:00");
  const data = await f.scheduleRepo().load();
  assert.equal(scheduleConflicts(data.events, [], "development-student").get(event.id)!.length, 1);
  await service.record(habit.id, today, "missed");
  await service.record(habit.id, today, "missed");
  items = await f.service().synchronize(range);
  const missed = items.find(item => item.habitId === habit.id && item.date === today)!;
  assert.equal(outcome(missed), "missed"); assert.equal(missed.event!.status, "requires-replanning");
  assert.equal(missed.event!.history.filter(entry => entry.kind === "missed").length, 1);
  assert.equal(outcome(items.find(item => item.habitId === other.id && item.date === today)!), "unrecorded");
  await service.replan(missed.event!, { ...event.slot, date: addDays(today, 1), start: "07:00", end: "07:01" }, { mode: "manual" });
  await service.record(habit.id, today, "completed");
  const reviewed = (await service.synchronize(range)).find(item => item.habitId === habit.id && item.date === today)!;
  assert.equal(outcome(reviewed), "review"); assert.equal(reviewed.event!.originalSlot.date, today);
  assert.equal(reviewed.event!.slot.date, addDays(today, 1));
  assert.equal(feedback([reviewed], habit.id, { date: today, time: "23:59" }).completed, 0);
  assert.equal(feedback([reviewed], habit.id, { date: today, time: "23:59" }).review, 1);
});
