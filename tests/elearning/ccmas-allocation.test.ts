import "../helpers/env";
import { it } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { elearningDb as db } from "@/lib/db/elearning";
import { courseScenario } from "../helpers/elearning-fixtures";
import { getStructureView } from "@/services/e-learning/dapu/curriculum/get-structure-view";
import { saveCourseSelection } from "@/services/e-learning/dapu/curriculum/save-course-selection";
import { linkCcmasProgramme, listCcmasProgrammes } from "@/services/e-learning/dapu/ccmas-reference";
import sourceReview from "@/lib/resources/ccmas/Engineering-CCMAS-2023-review.json";

it("preserves programme/level/semester allocation and table units while exposing source discrepancies", async () => {
  const f = await courseScenario();
  const placement = await db.curriculumCourse.findUniqueOrThrow({ where: { id: (await db.courseOffering.findUniqueOrThrow({ where: { id: f.offering.id } })).curriculumCourseId }, include: { curriculum: { include: { programme: { include: { department: true } } } } } });
  const programme = placement.curriculum.programme;
  const tag = randomUUID();
  const document = await db.cCMASDocument.create({ data: { name: `CCMAS-test-${tag}`, version: "2023", source: "test", fileReference: "supplied-2023.pdf", sha256: sourceReview.sourceSha256 } });
  const discipline = await db.cCMASDiscipline.create({ data: { documentId: document.id, name: "Engineering and Technology" } });
  const reference = await db.cCMASProgramme.create({ data: { disciplineId: discipline.id, name: "Computer Engineering", code: "CPE" } });
  assert.equal((await listCcmasProgrammes()).some(p => p.id === reference.id), false);
  await assert.rejects(linkCcmasProgramme(programme.id, reference.id), /import hasn't completed/);
  await db.cCMASImportBatch.create({ data: { documentId: document.id, jsonSha256: "test-fixture" } });
  await linkCcmasProgramme(programme.id, reference.id);
  assert.equal((await listCcmasProgrammes()).some(p => p.id === reference.id), true);
  const makeRow = async (code: string, level: number, units: number) => {
    const course = await db.cCMASCourse.create({ data: { documentId: document.id, code, title: `Reference ${code}`, creditUnits: units } });
    return db.cCMASProgrammeCourse.create({ data: { programmeId: reference.id, courseId: course.id, level, creditUnits: units, statusLetter: "C", courseType: "CORE", titleAsListed: course.title, sourcePage: 274 } });
  };
  const row = await makeRow("CPE 301", 300, 2);
  const otherLevel = await makeRow("CPE 101", 100, 3);
  const semester = await db.semester.create({ data: { academicSessionId: f.ctx.session!.id, sequence: 2, name: "Second", startDate: new Date("2027-01-01"), endDate: new Date("2027-06-01") } });
  const context = { collegeId: programme.department.collegeId, departmentId: programme.departmentId, programmeId: programme.id, level: 300, academicSessionId: f.ctx.session!.id, semesterId: semester.id };
  const view = await getStructureView(context);
  assert.deepEqual(view.ccmasCourses.map(c => c.id), [row.id]);
  assert.equal(view.ccmasCourses[0].creditUnits, 2);
  assert.ok(view.ccmasCourses[0].sourceWarnings.some(w => w.includes("units differ")));
  await assert.rejects(saveCourseSelection("test-dapu", context, { ccmasCourseIds: [otherLevel.id], electiveCourseIds: [] }), /aren't part/);
  const saved = await saveCourseSelection("test-dapu", context, { ccmasCourseIds: [row.id], electiveCourseIds: [] });
  await saveCourseSelection("test-dapu", context, { ccmasCourseIds: [row.id], electiveCourseIds: [] });
  const curriculum = await db.curriculum.findUniqueOrThrow({ where: { id: saved.curriculumId }, include: { courses: true } });
  assert.equal(curriculum.semesterId, semester.id);
  assert.equal(curriculum.programmeId, programme.id);
  assert.equal(curriculum.courses.length, 1);
  assert.equal(curriculum.courses[0].level, 300);
  assert.equal(curriculum.courses[0].creditUnits, 2);
  assert.equal((await db.curriculum.findUniqueOrThrow({ where: { id: placement.curriculumId } })).status, "PUBLISHED");
  assert.equal((await db.programme.findUniqueOrThrow({ where: { id: programme.id } })).departmentId, programme.departmentId);
  await assert.rejects(getStructureView({ ...context, departmentId: "unrelated-department" }), /don't match/);
  await assert.rejects(getStructureView({ ...context, academicSessionId: "unrelated-session" }), /doesn't belong/);
});
