// Explicit integration rehearsal. Creates NEW local-only databases; never resets existing databases.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
const tag = Date.now();
const coreName = `akadverse_reset_core_${tag}`;
const learningName = `akadverse_reset_learning_${tag}`;
const coreUrl = `postgresql://akadverse:akadverse_local_only@127.0.0.1:5433/${coreName}`;
const learningUrl = `postgresql://akadverse:akadverse_local_only@127.0.0.1:5433/${learningName}`;
const env = { ...process.env, DATABASE_URL: coreUrl, DIRECT_URL: coreUrl, ELEARNING_DATABASE_URL: learningUrl, ELEARNING_DIRECT_URL: learningUrl, TEST_DATABASE_URL: coreUrl, TEST_ELEARNING_DATABASE_URL: learningUrl, SUPABASE_URL: 'https://storage.akadverse.test', SUPABASE_SERVICE_ROLE_KEY: 'fixture', AI_SERVICE_URL: 'https://ai.akadverse.test', CONCEPT_EXPLAINER_API_URL: 'https://ai.akadverse.test', AI_SERVICE_API_KEY: 'fixture' };
const run = (cmd, args, input) => {
  const r = spawnSync(cmd, args, { env, input, encoding: undefined, maxBuffer: 32 * 1024 * 1024 });
  if (r.status !== 0) throw new Error(`${cmd} failed: ${String(r.stderr).slice(-2000)} ${String(r.stdout).slice(-1000)}`);
  return r.stdout;
};
const dockerBase = ['compose', '-f', 'for_Developers/docker-compose.yml', 'exec', '-T', 'postgres'];
for (const name of [coreName, learningName]) run('docker', [...dockerBase, 'createdb', '-U', 'akadverse', name]);
console.log('Created dedicated local rehearsal databases.');
run('npm', ['run', 'test:db:setup']);
run('node', ['--import', 'tsx', 'scripts/ccmas/import-ccmas.ts', 'src/lib/resources/ccmas/Engineering-CCMAS-2023.json']);
run('node', ['--import', 'tsx', 'tests/ccmas/reset-fixture.ts']);
const inventoryLog = String(run('node', ['--import', 'tsx', 'scripts/elearning-reset/inventory.ts']));
const inventoryPath = inventoryLog.match(/Private report: (.+)/)[1].trim();
const coreLog = String(run('node', ['scripts/elearning-reset/core-inventory.mjs']));
const corePath = coreLog.match(/Private report: (.+)/)[1].trim();
const inventory = JSON.parse(readFileSync(inventoryPath, 'utf8'));
const material = inventory.models.find(m => m.model === 'CourseMaterial').rows[0];
writeFileSync(`${inventoryPath}.storage.json`, JSON.stringify({ objects: [{ bucket: material.storageBucket, path: material.storagePath }], missing: [] }), { mode: 0o600 });
const folder = `.elearning-reset/rehearsal-${tag}`;
mkdirSync(folder, { mode: 0o700 });
const dumpPath = `${folder}/fixture.dump`;
writeFileSync(dumpPath, run('docker', [...dockerBase, 'pg_dump', '-U', 'akadverse', '-Fc', '--schema=public', learningName]), { mode: 0o600 });
const objectFile = `${folder}/fixture.bin`;
writeFileSync(objectFile, 'fixture!', { mode: 0o600 });
const sha = input => createHash('sha256').update(input).digest('hex');
const manifestPath = `${folder}/manifest.json`;
writeFileSync(manifestPath, JSON.stringify({ inventoryPath, dumpPath, dumpSha256: sha(readFileSync(dumpPath)), restoreVerified: false, objects: [{ materialId: material.id, bucket: material.storageBucket, path: material.storagePath, file: objectFile, size: 8, sha256: sha(readFileSync(objectFile)) }] }), { mode: 0o600 });
run('node', ['scripts/elearning-reset/verify-backup.mjs', manifestPath]);
const planPath = `${folder}/plan.json`;
run('node', ['scripts/elearning-reset/plan.mjs', inventoryPath, '--core-inventory', corePath, '--out', planPath]);
const planSha = sha(readFileSync(planPath));
const command = ['--import', 'tsx', '--import', './tests/ccmas/reset-fake-network.mjs', 'scripts/elearning-reset/execute.ts', '--plan', planPath, '--execute', '--approved-plan-sha', planSha, '--backup', manifestPath, '--core-inventory', corePath, '--maintenance-confirmed'];
const failed = spawnSync('node', command, { env: { ...env, RESET_REHEARSAL_FAIL_AI: '1' }, encoding: 'utf8' });
if (failed.status !== 1 || !failed.stderr.includes('HTTP 503')) throw new Error('AI failure did not fail closed');
const registrationsBeforeRetry = String(run('docker', [...dockerBase, 'psql', '-U', 'akadverse', '-d', learningName, '-Atc', 'SELECT count(*) FROM "CourseRegistration"'])).trim();
if (registrationsBeforeRetry !== '1') throw new Error('AI failure cleared academic records before cleanup succeeded');
const durableIntent = String(run('docker', [...dockerBase, 'psql', '-U', 'akadverse', '-d', learningName, '-Atc', 'SELECT "operation" FROM "AiIngestTask"'])).trim();
if (durableIntent !== 'DELETE') throw new Error('AI cleanup retry intent was not durable');
console.log('AI outage failed closed and preserved academic records; deletion intent persisted for retry.');
console.log(String(run('node', command)));
// Repeat the identical approval to verify safe restart after completion.
console.log(String(run('node', command)));
const notificationScope = String(run('docker', [...dockerBase, 'psql', '-U', 'akadverse', '-d', coreName, '-Atc', 'SELECT "scope", count(*) FROM "Notification" GROUP BY "scope"'])).trim();
if (notificationScope !== 'MARKETPLACE|1') throw new Error('Unrelated marketplace notification was modified');
const preserved = String(run('docker', [...dockerBase, 'psql', '-U', 'akadverse', '-d', learningName, '-Atc', 'SELECT count(DISTINCT "departmentId"), count(*) FROM "Program"'])).trim();
if (preserved !== '1|3') throw new Error('EIE programme hierarchy changed');
console.log(`PASS: reset and repeat-run preserved identity fingerprints, marketplace notification and EIE hierarchy. Artifacts: ${folder}`);
