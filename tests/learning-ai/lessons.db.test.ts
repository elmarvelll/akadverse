async function execute(studentId: string, runId: string, command: string, extra: Record<string, unknown> = {}) {
  const requestId = randomUUID();
  const queued = await lessons.queueLessonCommand(studentId, runId, { command, requestId, ...extra });
  const claimed = await worker.claimLessonAction(studentId); assert.equal(claimed?.id, queued.actionId);
  await worker.processLessonAction(claimed!);
  return elearningDb.learningLessonAction.findUniqueOrThrow({ where: { id: queued.actionId } });
}
